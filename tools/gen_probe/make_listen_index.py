#!/usr/bin/env python3
"""Write tools/gen_probe/listen_index.js from the A/B manifests (0.9.24).

Usage: make_listen_index.py [--docs DIR ...] [--out FILE] [--base TAG]
  --docs  directory with manifest_<tag>.tsv and the MIDI files; repeat for several
          runs. Default: docs/testing/0.9.24-base plus every docs/testing/0.9.24-cand-*
  --out   the JavaScript file that listen.html loads (default: tools/gen_probe/listen_index.js)
  --base  the reference version; every other tag is paired against it (default: base)

The index is generated, never edited by hand. It takes the absolute WAV paths
from each manifest's norm_wav_path column (the loudness-matched _norm.wav, outside
the repository) and the MIDI next to the manifest. Every path must exist, or the
script stops: a stale index is worse than none. Regenerate after a new candidate
manifest appears, or after the render folder moves.
"""
import argparse
import csv
import datetime
import glob
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def read_manifest(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--docs", action="append",
                    help="repeatable; default: 0.9.24-base and every 0.9.24-cand-* in docs/testing")
    ap.add_argument("--out", default=str(ROOT / "tools/gen_probe/listen_index.js"))
    ap.add_argument("--base", default="base")
    args = ap.parse_args()

    testing = ROOT / "docs/testing"
    docs_dirs = [Path(d).resolve() for d in args.docs] if args.docs else (
        [testing / "0.9.24-base"] + sorted(testing.glob("0.9.24-cand-*")))
    manifests = []  # (docs dir, manifest path)
    for d in docs_dirs:
        found = sorted(glob.glob(str(d / "manifest_*.tsv")))
        if not found:
            sys.exit(f"make_listen_index: no manifest_*.tsv in {d}")
        manifests += [(d, m) for m in found]

    tags = []
    takes = {}  # (genre, take) -> {"genre", "take", "versions": {tag: entry}}
    problems = []
    for docs, mpath in manifests:
        rows = read_manifest(mpath)
        if not rows or "tag" not in rows[0] or "norm_wav_path" not in rows[0]:
            sys.exit(f"make_listen_index: {mpath} has no tag/norm_wav_path columns (run loudness first)")
        for r in rows:
            tag = r["tag"]
            if tag not in tags:
                tags.append(tag)
            wav = Path(r["norm_wav_path"])
            mid = docs / (Path(r["file"]).stem + ".mid")  # MIDI sits next to its manifest
            if not wav.is_file():
                problems.append(f"missing WAV: {wav}")
            if not mid.is_file():
                problems.append(f"missing MIDI: {mid}")
            key = (r["genre"], r["take"])
            takes.setdefault(key, {"genre": r["genre"], "take": int(r["take"]), "versions": {}})
            takes[key]["versions"][tag] = {
                "name": wav.name,
                "url": wav.as_uri(),
                "path": str(wav),
                "midName": mid.name,
                "midUrl": mid.as_uri(),
                "midPath": str(mid),
                "rmsDb": float(r["norm_rms_dbfs"]) if r.get("norm_rms_dbfs") else None,
                "capped": r.get("norm_capped") == "1",
            }
    if problems:
        sys.exit("make_listen_index: refusing to write a stale index:\n  " + "\n  ".join(problems[:20]))

    if args.base not in tags:
        sys.exit(f"make_listen_index: reference tag {args.base!r} is not among {tags}")
    ordered = [args.base] + sorted(t for t in tags if t != args.base)
    take_list = sorted(takes.values(), key=lambda t: (t["genre"], t["take"]))
    pairs = []
    for cand in ordered[1:]:
        for t in take_list:
            if args.base in t["versions"] and cand in t["versions"]:
                pairs.append({"genre": t["genre"], "take": t["take"], "verA": args.base, "verB": cand})

    index = {
        "generated": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "docs": [str(d) for d in docs_dirs],
        "tags": ordered,
        "takes": take_list,
        "pairs": pairs,
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(index, ensure_ascii=False, indent=1)
    out.write_text(
        "// GENERATED by tools/gen_probe/make_listen_index.py. Do not edit by hand.\n"
        "window.LISTEN_INDEX = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"listen index: {out} tags={ordered} takes={len(take_list)} pairs={len(pairs)}")


if __name__ == "__main__":
    main()
