"""profiles.json -> self-contained C++17 constexpr header (flash only, no heap).

The header is a DATA layer. Wiring it into GroovePuter's idiom/recipe tables
is a separate, reviewed PR (see docs/AGENT_TASKS.md, PR-4).
"""
from __future__ import annotations

import hashlib
import json
import re
from datetime import date
from pathlib import Path

from . import __version__
from .features import INTERVAL_BUCKETS
from .profile import VariantProfile
from .schema import ROLES, STEPS

MAX_CELLS = 8


def _ident(v: str) -> str:
    return "k" + "".join(p.capitalize() for p in re.split(r"[^A-Za-z0-9]+", v) if p)


def _q8(x: float | None, scale: float = 255.0) -> int:
    if x is None:
        return 0
    return max(0, min(255, int(round(x * scale))))


def generate_header(profiles: dict[str, VariantProfile], meta: dict, namespace: str = "gp::genre_lab") -> str:
    src_hash = hashlib.sha256(json.dumps({k: p.to_json() for k, p in profiles.items()},
                                         sort_keys=True).encode()).hexdigest()[:12]
    roles_enum = ", ".join(r.capitalize() for r in ROLES)
    out = [
        "// AUTO-GENERATED by gplab codegen. Do not edit by hand.",
        f"// tool {__version__}, generated {date.today().isoformat()}, profiles sha256:{src_hash}",
        f"// corpus: {meta.get('corpus', 'unknown')}",
        "// Quantization: probabilities and frequencies are uint8 (value/255).",
        "#pragma once",
        "#include <cstdint>",
        "",
        f"namespace {namespace} {{",
        "",
        f"enum class Role : uint8_t {{ {roles_enum}, Count }};",
        f"inline constexpr uint8_t kRoleCount = {len(ROLES)};",
        f"inline constexpr uint8_t kSteps = {STEPS};",
        f"inline constexpr uint8_t kMaxCells = {MAX_CELLS};",
        f"inline constexpr uint8_t kIntervalBuckets = {len(INTERVAL_BUCKETS)};  // "
        + ", ".join(INTERVAL_BUCKETS),
        "",
        "struct RhythmCell { uint16_t mask; uint8_t weight; };  // bit s = onset at step s",
        "",
        "struct RoleProfile {",
        "  uint8_t stepProb[kSteps];      // P(onset) per step",
        "  uint8_t densityX16;            // mean hits per bar * 16",
        "  uint16_t protectedMask;        // steps the variant (almost) always plays",
        "  RhythmCell cells[kMaxCells];   // frequent whole-bar patterns",
        "  uint8_t cellCount;",
        "};",
        "",
        "struct BassProfile {",
        "  uint8_t restQ;                 // share of silent steps",
        "  uint8_t durX16;                // mean note length in steps * 16",
        "  uint8_t kickOverlapQ;          // share of bass onsets on kick steps",
        "  uint8_t medianPitch;           // MIDI note, 0 = unknown",
        "  uint8_t intervals[kIntervalBuckets];",
        "};",
        "",
        "struct VariantProfile {",
        "  const char* id;",
        "  uint8_t swingPctX2;            // swing % * 2 (100 = straight 50%)",
        "  uint16_t sources;              // tracks the profile was measured on",
        "  RoleProfile roles[kRoleCount];",
        "  BassProfile bass;",
        "};",
        "",
    ]
    names = []
    for v, p in sorted(profiles.items()):
        name = _ident(v)
        names.append(name)
        out.append(f"inline constexpr VariantProfile {name} = {{")
        out.append(f'  "{v}", {int(round((p.swing[0] or 50.0) * 2))}, {p.n_sources},')
        out.append("  {")
        for r in ROLES:
            probs = ", ".join(str(_q8(x)) for x in p.step_prob[r])
            dens = max(0, min(255, int(round(p.density[r][0] * 16))))
            pmask = sum(1 << s for s in p.protected.get(r, []))
            cells = p.cells.get(r, [])[:MAX_CELLS]
            cell_s = ", ".join(f"{{0x{int(m):04X}, {_q8(fq)}}}" for m, fq in cells) or "{0, 0}"
            out.append(f"    /* {r:5s} */ {{ {{{probs}}}, {dens}, 0x{pmask:04X}, "
                       f"{{{cell_s}}}, {len(cells)} }},")
        out.append("  },")
        b = p.bass or {}
        iv = ", ".join(str(_q8(x)) for x in (b.get("intervals") or [0.0] * len(INTERVAL_BUCKETS)))
        out.append(f"  {{ {_q8(b.get('rest'))}, {max(0, min(255, int(round((b.get('dur') or 0) * 16))))}, "
                   f"{_q8(b.get('kick_overlap'))}, {int(round(b.get('median_pitch') or 0))}, {{{iv}}} }}")
        out.append("};")
        out.append("")
    out.append(f"inline constexpr const VariantProfile* kVariants[] = {{ {', '.join('&' + n for n in names)} }};")
    out.append(f"inline constexpr uint8_t kVariantCount = {len(names)};")
    out.append(f"static_assert(sizeof(VariantProfile) <= 512, \"profile must stay compact\");")
    out.append("")
    out.append(f"}}  // namespace {namespace}")
    return "\n".join(out) + "\n"


def write_header(profiles, meta, path) -> int:
    text = generate_header(profiles, meta)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(text, encoding="utf-8")
    return len(text)
